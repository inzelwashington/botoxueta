export function madLevel(mad){
  const v = Math.max(0, Math.min(100, mad || 0));
  for (let i = 0; i < MAD_LEVELS.length; i++) if (v < MAD_LEVELS[i].max) return i;
  return MAD_LEVELS.length - 1;
}
export function madInfo(mad){ return MAD_LEVELS[madLevel(mad)]; }

