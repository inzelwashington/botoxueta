/** реплика рассказчика под текущий уровень бреда (или null) */
export function narratorVoice(mad, chance = 0.55){
  if (Math.random() > chance) return null;
  const lvl = madLevel(mad);
  const pool = VOICE[lvl] || VOICE[0];
  const alien = lvl >= 4 && Math.random() < 0.35;
  return { text: pick(pool), level: lvl, alien };
}

