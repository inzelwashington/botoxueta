/** текст события с учётом бреда */
export function eventText(ev, mad){
  const variants = MAD_TEXT[ev.id];
  let base = ev.text;
  if (variants && variants.length){
    const lvl = madLevel(mad);
    base = variants[Math.min(lvl, variants.length - 1)];
    // добавляем живую физиономию Сурдина к тексту, если он в событии
    if (ev.who === 'sur' && lvl >= 2 && Math.random() < 0.5){
      base += ' <span class="said">Сурдин: «Это, кстати, отличный пример гравитационного взаимодействия».</span>';
    }
  }
  const sfx = staticSuffix(mad);
  if (sfx) base += ` <span style="color:#5fd7ff;opacity:.75">${sfx}</span>`;
  return base;
}

