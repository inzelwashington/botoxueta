/* =====================================================================
   СОБЫТИЯ РЕЙСА
   ---------------------------------------------------------------------
   Схема события:
     id, title, text, tag('danger'|'weird'|'good'|''), who('sur'|'vas'|null),
     weight — базовый вес, cond(S) — показывать ли,
     choices: [{ label, sub, cost, req(S), rizz:bool, kb:bool, mg, run(S) }]
   run() возвращает { log, toasts, effects:[] } — движок сам всё применит.
   ===================================================================== */

const R = (min, max) => min + Math.random() * (max - min);

/* ---------- маленькие генераторы «последствий» ---------- */
function log(text, cls = ''){
  return { kind: 'log', text, cls };
}
function toast(text, cls = ''){
  return { kind: 'toast', text, cls };
}

